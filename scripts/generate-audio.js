// Pre-generates the game's audio with ElevenLabs, so the browser never needs an API key:
// one speech clip per line in public/announcements.js, plus the alarm and crowd ambience sound effects.
// Put ELEVENLABS_API_KEY (or ELEVEN_API_KEY) in .env or .env.local, then run `npm run audio`.
// Existing files are kept, to save credits; pass --force to regenerate them.
const fs = require('fs');
const path = require('path');
const lines = require('../public/announcements');

const key = process.env.ELEVENLABS_API_KEY || process.env.ELEVEN_API_KEY;
if (!key) {
  console.error('Set ELEVENLABS_API_KEY in .env or .env.local first.');
  process.exit(1);
}
const voice = process.env.ELEVENLABS_VOICE_ID || 'JBFqnCBsd6RMkjVDRZzb';
const model = process.env.ELEVENLABS_MODEL_ID || 'eleven_multilingual_v2';
const force = process.argv.includes('--force');
const dir = path.join(__dirname, '..', 'public', 'audio');
const api = 'https://api.elevenlabs.io/v1';
const sounds = {
  alarm: { text: 'Two-tone electronic evacuation alarm echoing in a large indoor stadium concourse, urgent', duration_seconds: 3 },
  ambience: { text: 'Large crowd murmuring and walking through an indoor stadium concourse, echoing footsteps, no music, no voices standing out', duration_seconds: 12, loop: true },
};
const jobs = [
  ...Object.entries(lines).map(([id, text]) => [id, `${api}/text-to-speech/${voice}`, { text, model_id: model }]),
  ...Object.entries(sounds).map(([id, body]) => [id, `${api}/sound-generation`, { ...body, model_id: 'eleven_text_to_sound_v2' }]),
];

(async () => {
  for (const [id, url, body] of jobs) {
    const file = path.join(dir, `${id}.mp3`);
    if (fs.existsSync(file) && !force) continue;
    const res = await fetch(`${url}?output_format=mp3_44100_128`, {
      method: 'POST',
      headers: { 'xi-api-key': key, 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    });
    if (!res.ok) {
      console.error(`${id}: ElevenLabs answered ${res.status}: ${await res.text()}`);
      process.exit(1);
    }
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
    console.log(`wrote public/audio/${id}.mp3`);
  }
  const present = jobs.map(([id]) => id).filter(id => fs.existsSync(path.join(dir, `${id}.mp3`)));
  fs.writeFileSync(path.join(dir, 'clips.js'),
    `// Generated by scripts/generate-audio.js (speech: ${model}, voice ${voice}): the audio clips present in this folder.\nwindow.CrowdAudioClips = ${JSON.stringify(present)};\n`);
})();
