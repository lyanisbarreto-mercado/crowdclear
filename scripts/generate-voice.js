// Pre-generates the announcement clips with ElevenLabs, so the browser never needs an API key.
// Put ELEVENLABS_API_KEY in .env, then run `npm run voice`.
const fs = require('fs');
const path = require('path');
const lines = require('../public/announcements');

const key = process.env.ELEVENLABS_API_KEY;
if (!key) {
  console.error('Set ELEVENLABS_API_KEY in .env first.');
  process.exit(1);
}
const voice = process.env.ELEVENLABS_VOICE_ID || 'JBFqnCBsd6RMkjVDRZzb';
const model = process.env.ELEVENLABS_MODEL_ID || 'eleven_multilingual_v2';
const dir = path.join(__dirname, '..', 'public', 'audio');

(async () => {
  const made = [];
  for (const [id, text] of Object.entries(lines)) {
    const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voice}?output_format=mp3_44100_128`, {
      method: 'POST',
      headers: { 'xi-api-key': key, 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, model_id: model }),
    });
    if (!res.ok) {
      console.error(`${id}: ElevenLabs answered ${res.status}: ${await res.text()}`);
      process.exit(1);
    }
    fs.writeFileSync(path.join(dir, `${id}.mp3`), Buffer.from(await res.arrayBuffer()));
    made.push(id);
    console.log(`wrote public/audio/${id}.mp3`);
  }
  fs.writeFileSync(path.join(dir, 'clips.js'),
    `// Generated by scripts/generate-voice.js (${model}, voice ${voice}): the announcement clips present in this folder.\nwindow.CrowdVoiceClips = ${JSON.stringify(made)};\n`);
})();
